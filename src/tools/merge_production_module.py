"""Merge the four DADG modules into one production module.

Usage: python merge_production_module.py [--modules <Modules dir>] [--target-id DellarteDellaGuerra.Merged]

Copies Core, DellarteDellaGuerra, DellarteDellaGuerraMap and DellarteDellaGuerraScenes (in load
order, later modules win on path collisions) into Modules/<target-id>, leaving out sources and
dev folders, then generates a single SubModule.xml and ModuleData/project.mbproj.
"""
import argparse
import os
import re
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SOURCE_MODULES = ['DellarteDellaGuerra.Core', 'DellarteDellaGuerra', 'DellarteDellaGuerraMap', 'DellarteDellaGuerraScenes']
TOP_LEVEL_DIR_EXCLUDES = {
    '.git', '.github', '.githooks', '.superpowers', '.worktrees', '.vs', 'src', 'AssetSources', '_asset_backups',
    'render-output', 'doc', 'log', 'tools', 'Tools', 'Shaders._prepublish', 'apm_modules', 'artifacts',
    'research', 'runtime-evidence', 'bin',
}
TOP_LEVEL_FILE_INCLUDES = {'LICENSE', 'CREDITS.md'}
FILE_SUFFIX_EXCLUDES = ('.log', '.rtemp', '.bak', '.stackdump', '.orig')
GENERATED_FILES = {Path('ModuleData/project.mbproj')}
BIN_FOLDER = Path('bin/Win64_Shipping_Client')


def same_content(a: Path, b: Path) -> bool:
    if a.stat().st_size != b.stat().st_size:
        return False
    with open(a, 'rb') as fa, open(b, 'rb') as fb:
        while True:
            ca, cb = fa.read(1 << 20), fb.read(1 << 20)
            if ca != cb:
                return False
            if not ca:
                return True


def module_files(module_dir: Path):
    for entry in sorted(module_dir.iterdir()):
        if entry.is_file():
            if entry.name in TOP_LEVEL_FILE_INCLUDES:
                yield entry
        elif entry.name not in TOP_LEVEL_DIR_EXCLUDES:
            for root, dirs, files in os.walk(entry):
                dirs[:] = sorted(d for d in dirs if d != '.git')
                for name in sorted(files):
                    if not name.endswith(FILE_SUFFIX_EXCLUDES):
                        yield Path(root) / name
    bin_dir = module_dir / BIN_FOLDER
    if bin_dir.is_dir():
        for path in sorted(bin_dir.rglob('*')):
            if path.is_file():
                yield path


def copy_modules(modules_dir: Path, target: Path):
    origin = {}
    collisions = []
    for module in SOURCE_MODULES:
        module_dir = modules_dir / module
        count = 0
        for src in module_files(module_dir):
            rel = src.relative_to(module_dir)
            if rel in GENERATED_FILES:
                continue
            dst = target / rel
            if rel in origin:
                if not same_content(dst, src):
                    collisions.append((rel, origin[rel], module))
                else:
                    origin[rel] = module
                    continue
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            origin[rel] = module
            count += 1
        print(f'{module}: {count} files')
    return collisions


def read_manifest(path: Path) -> ET.Element:
    return ET.parse(path).getroot()


def generate_submodule_xml(modules_dir: Path, target_id: str) -> str:
    manifests = [read_manifest(modules_dir / m / 'SubModule.xml') for m in SOURCE_MODULES]
    own_ids = set(SOURCE_MODULES)

    depended, metadata, seen_dep, seen_meta = [], [], set(), set()
    for manifest in manifests:
        for dep in manifest.iter('DependedModule'):
            if dep.get('Id') not in own_ids and dep.get('Id') not in seen_dep:
                seen_dep.add(dep.get('Id'))
                depended.append(dep)
        for meta in manifest.iter('DependedModuleMetadata'):
            if meta.get('id') not in own_ids and meta.get('id') not in seen_meta:
                seen_meta.add(meta.get('id'))
                metadata.append(meta)

    def attrs(element):
        return ' '.join(f'{k}="{v}"' for k, v in element.attrib.items())

    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by DellarteDellaGuerra.Core/src/tools/merge_production_module.py -->',
        '<Module>',
        f'  <Id value="{target_id}" />',
        '  <Name value="Dell\'Arte Della Guerra" />',
        f'  <Version value="{manifests[0].find("Version").get("value")}" />',
        '  <DefaultModule value="false" />',
        '  <ModuleCategory value="Singleplayer"/>',
        '  <ModuleType value="Community" />',
        '  <DependedModules>',
        *[f'    <DependedModule {attrs(d)}/>' for d in depended],
        '  </DependedModules>',
        '  <!-- https://github.com/BUTR/Bannerlord.BLSE#community-dependency-metadata -->',
        '  <DependedModuleMetadatas>',
        *[f'    <DependedModuleMetadata {attrs(m)}/>' for m in metadata],
        '  </DependedModuleMetadatas>',
        '  <SubModules>',
    ]
    for submodule in manifests[0].find('SubModules'):
        ET.indent(submodule, space='  ', level=2)
        lines.append('    ' + ET.tostring(submodule, encoding='unicode').rstrip())
    lines.append('  </SubModules>')
    lines.append('  <Xmls>')
    for module, manifest in zip(SOURCE_MODULES, manifests):
        nodes = manifest.findall('Xmls/XmlNode')
        if not nodes:
            continue
        lines.append(f'    <!-- {module} -->')
        for node in nodes:
            ET.indent(node, space='  ', level=2)
            lines.append('    ' + ET.tostring(node, encoding='unicode').rstrip())
    lines += ['  </Xmls>', '</Module>', '']
    return '\n'.join(lines)


def generate_mbproj(modules_dir: Path) -> str | None:
    # Keep the first project.mbproj as is and append the <file> entries the others add.
    merged, seen = None, set()
    for module in SOURCE_MODULES:
        path = modules_dir / module / 'ModuleData' / 'project.mbproj'
        if not path.is_file():
            continue
        text = path.read_text(encoding='utf-8-sig')
        entries = re.findall(r'^[ \t]*<file\b[^>]*/>', text, re.MULTILINE)
        names = [re.search(r'\bname="([^"]*)"', e).group(1) for e in entries]
        if merged is None:
            merged, seen = text, set(names)
            continue
        extra = [e.strip() for e, n in zip(entries, names) if n not in seen]
        seen.update(names)
        if extra:
            merged = merged.replace('</base>', ''.join(f'  {e}\n' for e in extra) + '</base>', 1)
    return merged


def retarget_nlog(target: Path, target_id: str):
    path = target / 'config' / 'nlog.config'
    if path.is_file():
        data = path.read_bytes()
        path.write_bytes(re.sub(rb'Modules/DellarteDellaGuerra[^/"]*/log/', f'Modules/{target_id}/log/'.encode(), data))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--modules', default=str(Path(__file__).resolve().parents[3]))
    parser.add_argument('--target-id', default='DellarteDellaGuerra.Merged')
    args = parser.parse_args()

    modules_dir = Path(args.modules)
    target = modules_dir / args.target_id
    for module in SOURCE_MODULES:
        if not (modules_dir / module / 'SubModule.xml').is_file():
            sys.exit(f'missing module: {modules_dir / module}')
    if target.exists():
        shutil.rmtree(target)
    target.mkdir()

    collisions = copy_modules(modules_dir, target)
    (target / 'SubModule.xml').write_text(generate_submodule_xml(modules_dir, args.target_id), encoding='utf-8')
    mbproj = generate_mbproj(modules_dir)
    if mbproj:
        (target / 'ModuleData' / 'project.mbproj').write_text(mbproj, encoding='utf-8')
    retarget_nlog(target, args.target_id)

    if collisions:
        print(f'{len(collisions)} path collisions with different content (later module wins):')
        for rel, earlier, later in collisions:
            print(f'  {rel.as_posix()}: {earlier} -> {later}')
    print(f'merged into {target}')


if __name__ == '__main__':
    main()
